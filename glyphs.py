def _parse(spec):
    d = {}
    for line in spec.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) == 1:
            d[' '] = ([], int(parts[0]) + 60)
            continue
        ch = parts[0]
        w = int(parts[1])
        coords = ' '.join(parts[2:])
        polys = []
        for seg in coords.split(';'):
            seg = seg.strip()
            if not seg:
                continue
            polys.append([tuple(map(int, p.split(','))) for p in seg.split()])
        d[ch] = (polys, w + 60)
    return d

